"""# **EXERCISE 5 — FastAPI Smart Responder**"""

from fastapi import FastAPI
from pydantic import BaseModel
import uvicorn

app = FastAPI()

class Query(BaseModel):
    message: str

@app.post("/respond")
def respond(q: Query):
    msg = q.message.lower()

    if "math" in msg:
        return {"reply": "Using calculator tool..."}

    if "date" in msg:
        return {"reply": "Fetching current date..."}

    return {"reply": "Default LLM response."}

if __name__ == "__main__":
    uvicorn.run(app, host="127.0.0.1", port=8000)