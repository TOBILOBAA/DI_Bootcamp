import time, numpy as np
from evaluate import load
from gen_infer import generate_response
from app import predict_sentiment, retrieve_topk  # reuse functions

# --- Dummy test set (replace with your own) ---
tests = [
  {"text": "Hate this new layout, impossible to read.", "label": "negative",
   "ref_reply": "Sorry about the layout trouble—try the compact view in Settings > Display."},
  {"text": "Update was smooth and fast, thanks!", "label": "positive",
   "ref_reply": "Great to hear! If you need anything else, we’re here."}
]

# Sentiment accuracy
correct = 0
latencies = []
for ex in tests:
    t0 = time.time()
    pred, _ = predict_sentiment(ex["text"])
    retrieved = retrieve_topk(ex["text"], k=3)
    # generate reply (optional)
    _ = generate_response(ex["text"], retrieved, pred, temperature=0.3)
    latencies.append(time.time() - t0)
    correct += int(pred == ex["label"])

acc = correct / len(tests)
print(f"Sentiment accuracy: {acc:.2f}")
print(f"Median latency: {np.median(latencies)*1000:.0f} ms")

# ROUGE against reference replies (if you have them)
rouge = load("rouge")
preds, refs = [], []
for ex in tests:
    pred, _ = predict_sentiment(ex["text"])
    retrieved = retrieve_topk(ex["text"], k=3)
    reply = generate_response(ex["text"], retrieved, pred, temperature=0.3)
    preds.append(reply)
